// WEB-ENG-3: maps every URL of the old website (www.mgims.ac.in/index.php/...) to its page on the new portal.
// Writes src/data/legacy_redirects.json (used by the /index.php/* route in the browser) and
// docs/legacy-redirects.nginx.conf (301 redirects for the web server, so search engines move to the new pages).
//
// Section pages already send their old keys to the right section (SectionedPage: `pages` and `aliases`), so an old
// page key K shown by the About page maps to /about-us/K. A key belongs to the page whose source mentions it.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const data = (name) => JSON.parse(fs.readFileSync(path.join(root, 'src/data', name), 'utf8'));
const source = (file) => fs.readFileSync(path.join(root, 'src/pages', file), 'utf8');

// Page → base path, in order of preference when several pages mention a key.
const PAGES = [
  ['AboutPage.tsx', '/about-us', 'institute.json'],
  ['HospitalPage.tsx', '/hospital', 'hospital.json'],
  ['AcademicsPage.tsx', '/academics', 'academics.json'],
  ['ResearchPage.tsx', '/research', 'research.json'],
  ['AccreditationsPage.tsx', '/accreditations', 'accreditations.json'],
  ['CommunityPage.tsx', '/community', 'community.json'],
].map(([file, base, own]) => ({ base, own, src: source(file) }));

// Old pages that are not section pages.
const SPECIAL = {
  home: '/', 'index.php': '/', Archives: '/news', contact: '/contact', 'contact-us': '/contact', 'contact-us-showall-1': '/contact',
  'getting-here': '/contact', 'non-teaching': '/academics/staff-lists', 'index-php-non-teaching': '/academics/staff-lists',
};

// The old site used /index.php/...; the key is the path (and query) of the old URL, lower case, without a trailing slash.
const oldKey = (url) => {
  try {
    const u = new URL(url);
    if (!/(^|\.)mgims\.ac\.in$/i.test(u.hostname)) return null;
    return `${u.pathname.replace(/\/+$/, '') || '/'}${u.search}`.toLowerCase();
  } catch {
    return null;
  }
};

const map = new Map();
const add = (url, target) => {
  const key = oldKey(url);
  if (key && key !== '/' && !map.has(key)) map.set(key, target);
};

for (const file of ['institute.json', 'hospital.json', 'academics.json', 'research.json', 'accreditations.json', 'community.json']) {
  for (const [key, page] of Object.entries(data(file))) {
    let target = SPECIAL[key];
    if (!target) {
      const mentions = PAGES.filter((p) => p.src.includes(`'${key}'`));
      const owner = mentions.find((p) => p.own === file) ?? mentions[0] ?? PAGES.find((p) => p.own === file);
      target = `${owner.base}/${key}`;
    }
    add(page.url, target);
  }
}
for (const n of data('notices_index.json')) add(n.url, `/notices/${n.id}`);
for (const d of data('departments.json')) add(d.url, `/departments/${d.id}`);
// Distinguished alumni have their own profile pages; the old site kept their profiles with the faculty pages.
const alumni = new Set(data('alumni_distinguished.json').map((a) => a.slug));
for (const f of data('faculty.json')) if (alumni.has(f.slug)) add(f.url, `/alumni/${encodeURIComponent(f.slug)}`);
for (const f of data('faculty.json')) add(f.url, `/faculty?select=${encodeURIComponent(f.slug)}`);

const entries = [...map.entries()].sort(([a], [b]) => a.localeCompare(b));
fs.writeFileSync(path.join(root, 'src/data/legacy_redirects.json'), JSON.stringify(Object.fromEntries(entries)));

const quote = (s) => `"${s.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;
fs.writeFileSync(
  path.join(root, 'docs/legacy-redirects.nginx.conf'),
  `# Generated by scripts/generate-legacy-redirects.mjs — do not edit by hand.
# 301 redirects from the old website's URLs to the new portal (FRS WEB-ENG-3). In the http block:
#   include /etc/nginx/conf.d/legacy-redirects.nginx.conf;
# and in the server block of www.mgims.ac.in:
#   if ($mgims_legacy_target) { return 301 $mgims_legacy_target; }
# Keys are lower case; $mgims_request_lc must hold the lower-cased $request_uri without a trailing slash (for
# example with the njs or lua module), or use $request_uri directly if the old links were all lower case.
map $mgims_request_lc $mgims_legacy_target {
    default "";
${entries.map(([from, to]) => `    ${quote(from)} ${quote(to)};`).join('\n')}
}
`,
);
console.log(`legacy redirects: ${entries.length} old URLs mapped`);
